/**
 * Единый общий каталог товаров и продуктов для ресторана «Голодный Турист»:
 * - Сохраняет точные названия, цены, единицы измерения и категории
 * - Устраняет дубликаты по названию
 * - Устанавливает привязку к ресторану «Голодный Турист»
 */
export function buildMergedGolodnyyTuristProducts(): Product[] {
  const mergedMap = new Map<string, Product>();
  let orderIndex = 1;

  // 1. Базовые продукты каталога
  for (const p of MINSK_PRODUCTS) {
    const key = p.name.trim().toLowerCase();
    const effectivePrice = p.pricesByRestaurant?.minsk || p.defaultPrice || '';
    mergedMap.set(key, {
      ...p,
      order: orderIndex++,
      restaurants: ['golodnyy_turist'],
      pricesByRestaurant: {
        golodnyy_turist: effectivePrice,
      },
    });
  }

  // 2. Дополнительные позиции каталога без повторов
  for (const p of ARMENIA_PRODUCTS) {
    const key = p.name.trim().toLowerCase();
    const armPrice = p.pricesByRestaurant?.armenia || p.defaultPrice || '';
    if (!mergedMap.has(key)) {
      mergedMap.set(key, {
        ...p,
        id: `gt-${p.id}`,
        order: orderIndex++,
        restaurants: ['golodnyy_turist'],
        pricesByRestaurant: {
          golodnyy_turist: armPrice,
        },
      });
    } else {
      // Если у существующего не было цены, а во втором источнике есть цена — дополняем
      const existing = mergedMap.get(key)!;
      const currentPrice = existing.pricesByRestaurant?.golodnyy_turist || existing.defaultPrice || '';
      if ((!currentPrice || parseFloat(currentPrice) <= 0) && armPrice && parseFloat(armPrice) > 0) {
        existing.defaultPrice = armPrice;
        existing.pricesByRestaurant = {
          ...existing.pricesByRestaurant,
          golodnyy_turist: armPrice,
        };
        existing.priceStatus = 'confirmed';
      }
    }
  }

  return Array.from(mergedMap.values());
}

